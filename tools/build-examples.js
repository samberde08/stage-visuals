'use strict';
// Bundles examples/*.stage.json into app/examples.js, so the page can offer them without fetching files
// (the online preview can only load scripts). Run after changing an example: node tools/build-examples.js
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname, '..', 'examples');
function bundle() {
  const out = {};
  fs.readdirSync(dir).filter((f) => f.endsWith('.stage.json')).sort().forEach((f) => { out[f.replace('.stage.json', '')] = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')); });
  return `/* Generated by tools/build-examples.js from examples/*.stage.json. Do not edit by hand. */\nwindow.StageExamples = ${JSON.stringify(out)};\n`;
}
if (require.main === module) fs.writeFileSync(path.join(__dirname, '..', 'app', 'examples.js'), bundle());
module.exports = { bundle };
